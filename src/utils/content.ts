// Site content edited in the admin. In CI, src/content/content.json is replaced by the
// published version from the server before the build; the committed file is seed data for local dev.
import data from '../content/content.json';
import type { Locale } from './i18n';

export interface Image {
  src: string;
  thumb: string | null;
  width: number | null;
  height: number | null;
}

export interface Actor {
  slug: string;
  name_et: string;
  name_ru: string;
  role_title_et: string;
  role_title_ru: string;
  bio_et: string;
  bio_ru: string;
  photo: Image | null;
}

export interface CastEntry {
  actor: string;
  role_et: string;
  role_ru: string;
}

export interface Play {
  slug: string;
  title_et: string;
  title_ru: string;
  genre_et: string;
  genre_ru: string;
  synopsis_et: string;
  synopsis_ru: string;
  duration: number | null;
  age_limit: string;
  archived: boolean;
  piletikeskus_ids: string[];
  poster: Image | null;
  cast: CastEntry[];
}

export interface Role {
  play: Play;
  role: string;
}

const content = data as unknown as { actors: Actor[]; plays: Play[]; updatedAt: string | null };

export const actors: Actor[] = content.actors;
export const plays: Play[] = content.plays;
export const activePlays: Play[] = plays.filter((p) => !p.archived);
export const contentUpdatedAt = content.updatedAt;

const actorsBySlug = new Map(actors.map((a) => [a.slug, a]));

/** Localised field, e.g. field(play, 'title', 'ru') → play.title_ru */
export function field<T extends object>(item: T, name: string, lang: Locale): string {
  return String((item as Record<string, unknown>)[`${name}_${lang}`] ?? '');
}

/** Cast with actor records resolved; entries whose actor no longer exists are skipped. */
export function castOf(play: Play, lang: Locale): { actor: Actor; role: string }[] {
  return play.cast.flatMap((c) => {
    const actor = actorsBySlug.get(c.actor);
    return actor ? [{ actor, role: lang === 'ru' ? c.role_ru : c.role_et }] : [];
  });
}

/** An actor's roles, split into current repertoire and archived productions. */
export function rolesOf(actorSlug: string, lang: Locale): { current: Role[]; past: Role[] } {
  const current: Role[] = [];
  const past: Role[] = [];
  for (const play of plays) {
    for (const c of play.cast) {
      if (c.actor === actorSlug) {
        (play.archived ? past : current).push({ play, role: lang === 'ru' ? c.role_ru : c.role_et });
      }
    }
  }
  return { current, past };
}

const PLACEHOLDERS = {
  actors: '/images/placeholder-actor.jpg',
  plays: '/images/placeholder-stage.jpg',
} as const;

// Long side of the thumbnails generated by the admin (server/public_html/admin/lib/images.php).
const THUMB_LONG_SIDE = { actors: 400, plays: 600 } as const;

/**
 * <img> attributes for an uploaded image: srcset with the thumbnail and the full size when both exist,
 * so the browser picks the smaller file for cards and grids.
 */
export function imageAttrs(image: Image | null, kind: 'actors' | 'plays', sizes: string) {
  if (!image) {
    return { src: PLACEHOLDERS[kind] };
  }
  const { src, thumb, width, height } = image;
  if (!thumb || !width || !height) {
    return { src };
  }
  const thumbWidth = Math.min(width, Math.round((width * THUMB_LONG_SIDE[kind]) / Math.max(width, height)));
  return {
    src,
    srcset: `${thumb} ${thumbWidth}w, ${src} ${width}w`,
    sizes,
    width,
    height,
  };
}
