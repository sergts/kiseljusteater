// Site content edited in the admin. In CI, src/content/content.json is replaced by the
// published version from the server before the build; the committed file is seed data for local dev.
import data from '../content/content.json';
import defaults from '../content/site-defaults.json';
import type { Locale } from './i18n';

export interface Image {
  src: string;
  thumb: string | null;
  width: number | null;
  height: number | null;
}

export interface Actor {
  slug: string;
  name_et: string;
  name_ru: string;
  name_en?: string;
  role_title_et: string;
  role_title_ru: string;
  role_title_en?: string;
  bio_et: string;
  bio_ru: string;
  bio_en?: string;
  photo: Image | null;
}

export interface CastEntry {
  actor: string;
  role_et: string;
  role_ru: string;
  role_en?: string;
}

export interface Play {
  slug: string;
  title_et: string;
  title_ru: string;
  title_en?: string;
  genre_et: string;
  genre_ru: string;
  genre_en?: string;
  synopsis_et: string;
  synopsis_ru: string;
  synopsis_en?: string;
  duration: number | null;
  age_limit: string;
  archived: boolean;
  piletikeskus_ids: string[];
  poster: Image | null;
  cast: CastEntry[];
}

/** A visitor-information block (afisha page), edited in the admin under "Инфо". */
export interface InfoBlock {
  title_et: string;
  title_ru: string;
  title_en?: string;
  body_et: string;
  body_ru: string;
  body_en?: string;
  /** One-line version for the "Before you buy" panel on play pages. */
  short_et?: string;
  short_ru?: string;
  short_en?: string;
  /** Shown in that panel (needs a short text). */
  play_page?: boolean;
  icon?: string;
  visible?: boolean;
}

export interface Contacts {
  address_et: string;
  address_ru: string;
  address_en?: string;
  phone: string;
  email: string;
}

export interface Role {
  play: Play;
  role: string;
}

const content = data as unknown as {
  actors: Actor[];
  plays: Play[];
  info?: InfoBlock[];
  contacts?: Contacts;
  updatedAt: string | null;
};

export const actors: Actor[] = content.actors;
export const plays: Play[] = content.plays;
export const activePlays: Play[] = plays.filter((p) => !p.archived);
export const contentUpdatedAt = content.updatedAt;

// Until the first publish that includes them, the built-in defaults are used.
export const infoBlocks: InfoBlock[] = (content.info ?? (defaults.info as InfoBlock[])).filter(
  (b) => b.visible !== false && b.body_et.trim() !== '',
);
export const contacts: Contacts = content.contacts ?? (defaults.contacts as Contacts);

const actorsBySlug = new Map(actors.map((a) => [a.slug, a]));

/** Localised field, e.g. field(play, 'title', 'ru') → play.title_ru (English falls back to Estonian). */
export function field<T extends object>(item: T, name: string, lang: Locale): string {
  const record = item as Record<string, unknown>;
  const value = record[`${name}_${lang}`];
  // English is optional in the admin: show the Estonian text until it is filled in.
  return String(value || (lang === 'en' ? record[`${name}_et`] : '') || '');
}

/** Cast with actor records resolved; entries whose actor no longer exists are skipped. */
export function castOf(play: Play, lang: Locale): { actor: Actor; role: string }[] {
  return play.cast.flatMap((c) => {
    const actor = actorsBySlug.get(c.actor);
    return actor ? [{ actor, role: field(c, 'role', lang) }] : [];
  });
}

/** An actor's roles, split into current repertoire and archived productions. */
export function rolesOf(actorSlug: string, lang: Locale): { current: Role[]; past: Role[] } {
  const current: Role[] = [];
  const past: Role[] = [];
  for (const play of plays) {
    for (const c of play.cast) {
      if (c.actor === actorSlug) {
        (play.archived ? past : current).push({ play, role: field(c, 'role', lang) });
      }
    }
  }
  return { current, past };
}

// Shown when an actor or play has no picture (a logo panel in the site's colours).
const PLACEHOLDERS = {
  actors: '/images/default-actor.svg',
  plays: '/images/default-play.svg',
} as const;

// Early versions of the site stored generated stand-in pictures under /images/actors and /images/plays
// (SVG data with a .jpg name, which browsers cannot show). Content that still points at them gets the default picture.
const isStandIn = (src: string) => /^\/images\/(actors|plays)\//.test(src) || src.startsWith('/images/placeholder');

// Long side of the thumbnails generated by the admin (server/public_html/admin/lib/images.php).
const THUMB_LONG_SIDE = { actors: 400, plays: 600 } as const;

/**
 * <img> attributes for an uploaded image: srcset with the thumbnail and the full size when both exist,
 * so the browser picks the smaller file for cards and grids.
 */
export function imageAttrs(image: Image | null, kind: 'actors' | 'plays', sizes: string) {
  if (!image || !image.src || isStandIn(image.src)) {
    return { src: PLACEHOLDERS[kind] };
  }
  const { src, thumb, width, height } = image;
  if (!thumb || !width || !height) {
    return { src };
  }
  const thumbWidth = Math.min(width, Math.round((width * THUMB_LONG_SIDE[kind]) / Math.max(width, height)));
  return {
    src,
    srcset: `${thumb} ${thumbWidth}w, ${src} ${width}w`,
    sizes,
    width,
    height,
  };
}
